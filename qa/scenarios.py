ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FOLDER = ROOT / 'qa' / 'datasets' / 'aml-v1'
Check = Literal['behavior', 'facts', 'source_integrity', 'model_payload', 'rule_selection']


class CatalogError(ValueError):
    """Fixed diagnostic code without source payloads or private path contents."""


def _require(condition: bool, code: str):
    if not condition:
        raise CatalogError(code)


def _distinct(values, code='DUPLICATE_VALUE'):
    _require(len(values) == len(set(values)), code)


class GoldenSum(StrictModel):
    currency: Currency
    value: Money
    tx_ids: Annotated[list[Identifier], Field(min_length=1)]

    @model_validator(mode='after')
    def unique_members(self):
        _distinct(self.tx_ids, 'DUPLICATE_AGGREGATE_MEMBER')
        return self


class Golden(StrictModel):
    fact_count: Annotated[int, Field(ge=1)]
    transaction_ids: Annotated[list[Identifier], Field(min_length=1)]
    sums: Annotated[list[GoldenSum], Field(min_length=1)]
    rules: Annotated[list[ApplicableRule], Field(min_length=1)]

    @model_validator(mode='after')
    def unique_items(self):
        _distinct(self.transaction_ids, 'DUPLICATE_GOLDEN_TRANSACTION')
        _distinct([item.currency for item in self.sums], 'DUPLICATE_GOLDEN_CURRENCY')
        _distinct([(r.citation.rule_id, r.citation.rule_version, r.citation.chunk_id)
                   for r in self.rules], 'DUPLICATE_GOLDEN_RULE')
        return self


class Scenario(StrictModel):
    case: Case
    title: Text
    rationale: Text
    split: Literal['calibration', 'heldout']
    fixture: Annotated[str, Field(pattern=r'^fixtures/[A-Za-z0-9][A-Za-z0-9_-]*$')]
    mode: Literal['demo', 'production']
    engine: Literal['template', 'local-model']
    dependency: Literal['healthy', 'unavailable', 'invalid_selection']
    expected_model_calls: Annotated[int, Field(ge=0, le=2)]
    source_mutations: list[Text]
    independence_basis: Text
    excluded_transaction_ids: list[Identifier]
    forbidden_prompt_strings: list[Text]
    applicable_checks: Annotated[list[Check], Field(min_length=1)]
    golden: Golden | None

    @model_validator(mode='after')
    def coherent(self):
        for items in (self.source_mutations, self.excluded_transaction_ids,
                      self.forbidden_prompt_strings, self.applicable_checks):
            _distinct(items)
        _require('behavior' in self.applicable_checks, 'BEHAVIOR_CHECK_REQUIRED')
        if self.case.expected_status == 'draft':
            _require(self.golden is not None and self.case.context is not None,
                     'DRAFT_REQUIRES_CONTEXT_AND_GOLDEN')
            _require(self.case.expected_retrieval is not None and
                     bool(self.case.expected_retrieval.ids), 'DRAFT_REQUIRES_RETRIEVAL')
            _require({'facts', 'rule_selection'} <= set(self.applicable_checks),
                     'DRAFT_REQUIRES_FACT_AND_RULE_CHECKS')
        else:
            _require(self.golden is None, 'NON_DRAFT_HAS_GOLDEN')
            _require(self.case.expected_reason_code is not None, 'REASON_REQUIRED')
            _require('facts' not in self.applicable_checks, 'NON_DRAFT_FACT_CHECK')
        if self.engine == 'template':
            _require(self.expected_model_calls == 0 and self.dependency == 'healthy',
                     'TEMPLATE_CANNOT_CALL_MODEL')
        if self.mode == 'production':
            _require(self.expected_model_calls == 0, 'UNAPPROVED_MODE_CANNOT_CALL_MODEL')
        return self


class Catalog(StrictModel):
    schema_version: Literal['1.0']
    dataset_version: Annotated[str, Field(pattern=r'^[0-9]+\.[0-9]+\.[0-9]+$')]
    dataset: Dataset
    category_notes: dict[Literal['A', 'B', 'C', 'D', 'E'], Text]
    independence_policy: Text
    cases: Annotated[list[Scenario], Field(min_length=2)]

    @model_validator(mode='after')
    def coverage_and_splits(self):
        _require(self.dataset.kind == 'synthetic_control', 'SYNTHETIC_DATASET_REQUIRED')
        sme = self.dataset.sme_acceptance
        _require(sme is not None and sme.status == 'pending' and sme.reviewer_id is None
                 and sme.reviewed_at is None and not sme.evidence_references and not sme.case_ids,
                 'SME_MUST_REMAIN_PENDING')
        _require(set(self.category_notes) == set('ABCDE'), 'CATEGORY_DEFINITIONS_REQUIRED')
        _distinct([s.case.id for s in self.cases], 'DUPLICATE_CASE_ID')
        _require({s.split for s in self.cases} == {'calibration', 'heldout'}, 'BOTH_SPLITS_REQUIRED')
        families = {}
        fixtures = {}
        incidents = {}
        for scenario in self.cases:
            family, split = scenario.case.independence_id, scenario.split
            _require(family not in families or families[family] == split, 'FAMILY_SPLIT_LEAKAGE')
            _require(scenario.fixture not in fixtures or fixtures[scenario.fixture] == split,
                     'FIXTURE_SPLIT_LEAKAGE')
            # Renaming a family must not turn variants of the same valid
            # incident into independent observations. Preserve malformed raw
            # requests: normalising them would erase their input-error oracle.
            incident = scenario.case.incident_id
            if classify_incident_id(incident) is None:
                _require(incident not in incidents or incidents[incident] == (family, split),
                         'INCIDENT_FAMILY_MISMATCH')
                incidents[incident] = (family, split)
            families[family], fixtures[scenario.fixture] = split, split
        return self


class ManifestFile(StrictModel):
    path: Text
    sha256: Digest
    bytes: Annotated[int, Field(ge=0, le=4 * 1024 * 1024)]


class Manifest(StrictModel):
    schema_version: Literal['1.0']
    dataset_version: Annotated[str, Field(pattern=r'^[0-9]+\.[0-9]+\.[0-9]+$')]
    files: Annotated[list[ManifestFile], Field(min_length=1, max_length=1000)]


def _member(folder: Path, relative: str) -> Path:
    # A portable path spelling rejects Windows drive/UNC/ADS and both traversal
    # syntaxes even when the validator is run on another operating system.
    _require(isinstance(relative, str) and bool(relative) and '\\' not in relative
             and ':' not in relative, 'UNSAFE_MEMBER_PATH')
    parts = PurePosixPath(relative).parts
    _require(not PurePosixPath(relative).is_absolute() and parts
             and all(p not in {'.', '..'} for p in parts)
             and '/'.join(parts) == relative, 'UNSAFE_MEMBER_PATH')
    candidate = folder
    for part in parts:
        candidate /= part
        info = candidate.lstat()
        _require(not stat.S_ISLNK(info.st_mode)
                 and not (getattr(info, 'st_file_attributes', 0) & 0x400), 'LINK_MEMBER_FORBIDDEN')
    _require(candidate.resolve().is_relative_to(folder), 'UNSAFE_MEMBER_PATH')
    _require(candidate.is_file() and candidate.stat().st_nlink == 1, 'UNSAFE_MEMBER_FILE')
    return candidate


def _read(folder: Path, relative: str) -> bytes:
    path = _member(folder, relative)
    _require(path.stat().st_size <= 4 * 1024 * 1024, 'MEMBER_TOO_LARGE')
    content = path.read_bytes()
    _require(len(content) <= 4 * 1024 * 1024, 'MEMBER_TOO_LARGE')
    return content


def _json(content: bytes):
    try:
        return strict_json(content)
    except (ValueError, UnicodeError, TypeError):
        raise CatalogError('INVALID_JSON') from None


def _context_and_golden(scenario: Scenario, contents: dict[str, bytes]):
    base = scenario.fixture + '/'
    policy = DemoPolicy.model_validate(_json(contents[base + 'policy.json']))
    manifest_bytes = contents[base + 'manifest.json']
    snapshot = SnapshotManifest.model_validate(_json(manifest_bytes))
    _require(sha256(manifest_bytes).hexdigest() == policy.snapshot_manifest_sha256,
             'POLICY_MANIFEST_HASH_MISMATCH')
    _require(snapshot.snapshot_id == policy.snapshot_id and snapshot.policy_id == policy.policy_id
             and snapshot.window == policy.window, 'POLICY_SNAPSHOT_MISMATCH')
    _require(len(snapshot.files) == len(FILES) and {r.name for r in snapshot.files} == set(FILES),
             'SNAPSHOT_FILE_SET_MISMATCH')
    _require(bool(snapshot.original_sources), 'SOURCE_LINEAGE_REQUIRED')
    _distinct([r.source for r in snapshot.original_sources], 'DUPLICATE_SOURCE_LINEAGE')
    age = (instant(snapshot.captured_at) - instant(policy.window.as_of)).total_seconds()
    _require(0 <= age <= policy.max_snapshot_age_seconds, 'SNAPSHOT_CAPTURE_WINDOW_MISMATCH')
    rows = {}
    for descriptor in snapshot.files:
        data = contents[base + descriptor.name]
        _require(sha256(data).hexdigest() == descriptor.content_sha256, 'SNAPSHOT_FILE_HASH_MISMATCH')
        parsed = _json(data)
        _require(type(parsed) is list and len(parsed) == descriptor.row_count,
                 'SNAPSHOT_ROW_COUNT_MISMATCH')
        rows[descriptor.name] = parsed
    context = scenario.case.context
    if context is None:
        return  # Broken business records are intentional negative fixtures.
    source_cases = [CaseRecord.model_validate(r) for r in rows['cases.json']]
    clients = [ClientProfile.model_validate(r) for r in rows['clients.json']]
    cards = [CardRecord.model_validate(r) for r in rows['cards.json']]
    transactions = [TransactionRecord.model_validate(r) for r in rows['transactions.json']]
    for records, key in ((source_cases, 'incident_id'), (source_cases, 'case_id'),
                         (clients, 'client_id'), (cards, 'card_id'), (transactions, 'tx_id')):
        _distinct([getattr(r, key) for r in records], 'CONTEXT_SOURCE_DUPLICATE')
    selected_case = [r for r in source_cases if r.incident_id == scenario.case.incident_id]
    _require(len(selected_case) == 1, 'CONTEXT_INCIDENT_NOT_IN_SOURCE')
    incident = selected_case[0]
    selected_clients = [r for r in clients if r.client_id == incident.client_id]
    selected_cards = [r for r in cards if r.client_id == incident.client_id]
    selected_transactions = [r for r in transactions if r.client_id == incident.client_id and
        instant(policy.window.start_inclusive) <= instant(r.timestamp) < instant(policy.window.end_exclusive)]
    expected_sources = [dict(source=r.name, version=r.content_sha256, content_sha256=r.content_sha256)
                        for r in snapshot.files]
    _require(len(selected_clients) == 1 and context.client == selected_clients[0]
             and context.client_id == incident.client_id and context.cards == selected_cards
             and context.transactions == selected_transactions
             and context.window == policy.window and context.policy_version == policy.policy_id
             and context.snapshot.snapshot_id == snapshot.snapshot_id
             and context.snapshot.captured_at == snapshot.captured_at
             and [r.model_dump() for r in context.snapshot.sources] == expected_sources
             and context.data_completeness == 'full' and context.consistency == 'consistent'
             and not context.missing_fields, 'CONTEXT_SOURCE_MISMATCH')
    all_ids = {r.tx_id for r in transactions}
    selected_ids = {r.tx_id for r in selected_transactions}
    _require(set(scenario.excluded_transaction_ids) <= all_ids - selected_ids,
             'EXCLUDED_TRANSACTION_MISMATCH')
    golden = scenario.golden
    if golden is None:
        return
    _require(set(golden.transaction_ids) == selected_ids, 'GOLDEN_TRANSACTION_MISMATCH')
    currencies = {r.currency for r in selected_transactions}
    _require({r.currency for r in golden.sums} == currencies, 'GOLDEN_CURRENCY_MISMATCH')
    _require(golden.fact_count == 3 + len(selected_ids) + 1 + len(currencies), 'GOLDEN_FACT_COUNT_MISMATCH')
    with localcontext() as decimal_context:
        decimal_context.prec = 170 + len(str(len(selected_transactions)))
        for aggregate in golden.sums:
            members = [r for r in selected_transactions if r.currency == aggregate.currency]
            _require(set(aggregate.tx_ids) == {r.tx_id for r in members}, 'GOLDEN_AGGREGATE_MEMBERS_MISMATCH')
            _require(Decimal(aggregate.value) == sum((Decimal(r.amount) for r in members), Decimal(0)),
                     'GOLDEN_SUM_MISMATCH')
    _golden_rules(scenario, rows['rules.json'], policy, incident.alert_type)


def _golden_rules(scenario: Scenario, sources: list, policy: DemoPolicy, alert_type: str):
    golden = scenario.golden
    allowed = set(policy.applicability.get(alert_type, []))
    _require({r.citation.rule_id for r in golden.rules} == allowed, 'GOLDEN_POLICY_RULE_MISMATCH')
    as_of = instant(policy.window.as_of).astimezone(timezone.utc).date().isoformat()
    for rule in golden.rules:
        citation = rule.citation
        matches = [r for r in sources if isinstance(r, dict) and r.get('rule_id') == citation.rule_id
                   and r.get('version') == citation.rule_version]
        _require(len(matches) == 1, 'GOLDEN_RULE_EDITION_MISMATCH')
        source = matches[0]
        _require(source.get('regulation_ref') == citation.source_ref
                 and source['effective_from'] <= as_of
                 and (source.get('effective_until') is None or as_of < source['effective_until']),
                 'GOLDEN_RULE_SOURCE_MISMATCH')
        text = source['text']
        start = text.find(rule.rule_text)
        _require(start >= 0 and text.find(rule.rule_text, start + 1) < 0, 'GOLDEN_RULE_TEXT_MISMATCH')
        digest = sha256(rule.rule_text.encode('utf-8')).hexdigest()
        identity = dict(rule_id=citation.rule_id, version=citation.rule_version,
                        source_ref=citation.source_ref, char_start=start,
                        char_end=start + len(rule.rule_text), text_sha256=digest)
        import json
        chunk = 'chunk-' + sha256(json.dumps(identity, ensure_ascii=False, sort_keys=True,
                                           separators=(',', ':')).encode('utf-8')).hexdigest()
        _require(citation.content_sha256 == digest and citation.chunk_id == chunk, 'GOLDEN_CITATION_MISMATCH')
    retrieval = scenario.case.expected_retrieval
    expected_ids = {r.citation.rule_id if retrieval.namespace == 'rule_id' else r.citation.source_ref
                    for r in golden.rules}
    _require(set(retrieval.ids) == expected_ids, 'GOLDEN_RETRIEVAL_MISMATCH')


def load_catalog(folder: Path = DEFAULT_FOLDER) -> Catalog:
    """Validate the complete frozen package before returning any scenario.

    Temporary local folders are supported for destructive fixture tests. No
    environment selection, network call, dependency startup or file write occurs.
    """
    try:
        folder = Path(folder)
        info = folder.lstat()
        _require(not folder.is_symlink() and not (getattr(info, 'st_file_attributes', 0) & 0x400),
                 'LINK_FOLDER_FORBIDDEN')
        folder = folder.resolve(strict=True)
        manifest = Manifest.model_validate(_json(_read(folder, 'manifest.json')))
        paths = [r.path for r in manifest.files]
        _distinct([p.casefold() for p in paths], 'DUPLICATE_MANIFEST_MEMBER')
        contents = {}
        for descriptor in manifest.files:
            # Only data and its documented reconstruction recipe may be members.
            _require(descriptor.path in {'cases.json', 'schema.json', 'README.md', 'build_fixtures.py'}
                     or re.fullmatch(r'fixtures/[A-Za-z0-9][A-Za-z0-9_-]*/(?:policy|manifest|cases|clients|cards|transactions|rules)\.json',
                                     descriptor.path) is not None, 'UNEXPECTED_MANIFEST_MEMBER')
            data = _read(folder, descriptor.path)
            _require(len(data) == descriptor.bytes and sha256(data).hexdigest() == descriptor.sha256,
                     'MANIFEST_HASH_MISMATCH')
            contents[descriptor.path] = data
        _require({'cases.json', 'schema.json'} <= contents.keys(), 'CATALOG_MEMBERS_MISSING')
        catalog = Catalog.model_validate(_json(contents['cases.json']))
        _require(catalog.dataset_version == manifest.dataset_version, 'DATASET_VERSION_MISMATCH')
        _require(_json(contents['schema.json']) == Catalog.model_json_schema(), 'CATALOG_SCHEMA_MISMATCH')
        expected = {s.fixture + '/' + name for s in catalog.cases for name in (*FILES, 'policy.json', 'manifest.json')}
        actual = {name for name in contents if name.startswith('fixtures/')}
        _require(expected == actual, 'FIXTURE_MEMBERS_MISMATCH')
        # Unlisted artifacts are not silently read later by another runner.
        on_disk = {p.relative_to(folder).as_posix() for p in folder.rglob('*')
                   if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc'}
        _require(on_disk == set(paths) | {'manifest.json'}, 'UNLISTED_DATASET_MEMBER')
        for scenario in catalog.cases:
            _context_and_golden(scenario, contents)
        return catalog
    except CatalogError:
        raise
    except (OSError, RuntimeError, ValueError, TypeError, KeyError, AttributeError, ValidationError):
        raise CatalogError('INVALID_CATALOG') from None
