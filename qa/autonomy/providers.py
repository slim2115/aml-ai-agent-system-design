"""Fixed local Ollama proposer for a bounded synthetic candidate experiment.

One invocation is one transport call; no repairs or provider retries are hidden
inside this adapter. The caller reserves its budget before invoking it. The
token reservation is a conservative accounting allowance, not an exact input
tokenizer or a guarantee that the separate Ollama server stops on client exit.
"""
from copy import deepcopy
import http.client
import json
import math
import time
from types import SimpleNamespace

from qa.tools import run_llm
from src.config import LLMConfig
from src.runtime.transport import LocalOllamaTransport, TransportFailure, strict_json


CASE_IDS = frozenset(run_llm.DRAFT_IDS)
REPAIR_CODES = frozenset({'INVALID_MODEL_JSON', 'INVALID_MODEL_RESPONSE',
                         'INCOMPLETE_OR_UNKNOWN_SELECTION'})
MODEL = run_llm.MODEL
EXPECTED_DIGEST = run_llm.EXPECTED_DIGEST
RESERVE_TOKENS = 16384
MAX_RESPONSE_TOKENS = 512


class _BoundedRecordingConnection(run_llm.RecordingHTTPConnection):
    def request(self, method, path, body, headers):
        # These values are generated by the reviewed transport. Never accept a
        # URL, model, tool declaration or options object from candidate output.
        value = strict_json(body.decode('utf-8'))
        if (method != 'POST' or path != '/api/chat' or value.get('model') != MODEL
                or value.get('stream') is not False
                or value.get('options') != {'temperature': 0}
                or set(value) != {'model', 'stream', 'format', 'options', 'messages'}):
            raise TransportFailure('NOT_READY')
        value['options']['num_predict'] = MAX_RESPONSE_TOKENS
        actual = json.dumps(value, ensure_ascii=False, allow_nan=False).encode('utf-8')
        if len(actual) > LocalOllamaTransport.MAX_BYTES:
            raise TransportFailure('NOT_READY')
        return super().request(method, path, actual, headers)


def _token_usage(record):
    reply = record.get('response_json')
    if (record.get('http_status') != 200 or type(reply) is not dict
            or reply.get('model') != MODEL):
        return None
    values = (reply.get('prompt_eval_count'), reply.get('eval_count'))
    if not all(type(value) is int and 0 <= value <= 10_000_000 for value in values):
        return None
    return sum(values)


class OllamaProposer:
    """Generate constrained candidate JSON against a literal loopback service.

    ``identity`` must be checked by the owner before and after a live batch.
    Raw synthetic wire records are exposed only for the owner's local evidence
    directory; do not place them into operational logs or publish them to Git.
    """

    reserve_tokens = RESERVE_TOKENS
    max_response_tokens = MAX_RESPONSE_TOKENS

    def __init__(self, candidates, *, clock=time.monotonic,
                 connection_type=http.client.HTTPConnection):
        self._candidates = candidates
        self._records = []
        self._clock = clock
        # Only llm is consumed by LocalOllamaTransport. Construct it directly:
        # no .env, QA runtime settings, proxy or user-provided model is loaded.
        settings = SimpleNamespace(llm=LLMConfig(
            base_url='http://127.0.0.1:11434', model_name=MODEL,
            embedding_model_name='unused-in-constrained-proposer',
            embedding_model_path='', embedding_manifest_path=''))
        self._transport = LocalOllamaTransport(settings, clock=clock,
            connection_factory=lambda host, port, **kwargs: _BoundedRecordingConnection(
                host, port, records=self._records, connection_type=connection_type, **kwargs))

    @property
    def attempts(self):
        return deepcopy(self._records)

    def identity(self):
        """Read the fixed model digest and server metadata; never pull a model."""
        return run_llm.identity()

    def __call__(self, case_id, attempt_index, feedback, deadline):
        start = len(self._records)
        outcome, raw = 'error', None
        try:
            if (type(case_id) is not str or case_id not in CASE_IDS
                    or type(attempt_index) is not int or not 1 <= attempt_index <= 3
                    or type(feedback) is not tuple or len(feedback) > len(REPAIR_CODES)
                    or any(type(code) is not str or code not in REPAIR_CODES for code in feedback)
                    or len(set(feedback)) != len(feedback)
                    or type(deadline) not in (float, int) or not math.isfinite(deadline)):
                return {'outcome': 'error', 'raw': None, 'tokens': None}
            payload = deepcopy(self._candidates.payload(case_id))
            schema = deepcopy(self._candidates.schema(case_id))
            if type(payload) is not dict or type(schema) is not dict:
                return {'outcome': 'error', 'raw': None, 'tokens': None}
            if feedback:
                # Only fixed validator codes are returned to the proposer.
                # The rejected response and the independent oracle stay out.
                payload['validation_failure'] = list(feedback)
            raw = self._transport.complete(payload, schema, deadline=deadline)
            records = self._records[start:]
            reply = records[0].get('response_json') if len(records) == 1 else None
            if (type(reply) is not dict or records[0].get('http_status') != 200
                    or reply.get('model') != MODEL or reply.get('done') is not True
                    or type(reply.get('eval_count')) is int
                    and reply['eval_count'] > MAX_RESPONSE_TOKENS):
                # num_predict is a server instruction, not a local hard kill.
                # Detect reported overruns without discarding their usage.
                raw = None
            else:
                outcome = 'completed'
        except TransportFailure as exc:
            outcome = 'timeout' if exc.code == 'DEADLINE_EXCEEDED' else 'error'
            raw = None
        except Exception:
            # The synthetic input may be malformed, but arbitrary exception
            # messages/paths are not part of the public provider contract.
            raw = None
        records = self._records[start:]
        tokens = _token_usage(records[0]) if len(records) == 1 else None
        return {'outcome': outcome, 'raw': raw, 'tokens': tokens}
