"""Transactional SQLite persistence for the explicitly local workflow simulator.

Each operation opens/closes its own connection. Trusted worker transitions are
separate from principal-authorized user operations. No model response, source
payload or raw exception is written to audit events.
"""
from contextlib import closing, contextmanager
from datetime import datetime, timedelta, timezone
import json
import math
from pathlib import Path
import re
import sqlite3
import uuid

from pydantic import ValidationError

from src.contracts.semantics import canonical_digest, validate_job, validate_job_transition
from src.contracts.v1 import ADAPTERS, CreateJobRequest, DecisionRequest, ReportRef, instant
from src.runtime.events import RunEvent
from src.qa_profile import get_qa_profile
from .auth import Principal


WORKFLOW_ROOT = Path(__file__).resolve().parents[2] / 'var' / 'workflow'
ACTIVE = ('queued', 'running')
MAX_RUNTIME_EVENTS = 32


class WorkflowError(ValueError):
    """Public code only; raw payloads and SQLite errors must not escape."""
    def __init__(self, code: str):
        self.code = code
        super().__init__(code)


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec='microseconds').replace('+00:00', 'Z')


def _json(value) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False)


def _wire(value) -> dict:
    return value.model_dump(mode='json') if hasattr(value, 'model_dump') else value


def _validated(adapter: str, value) -> dict:
    try:
        return ADAPTERS[adapter].validate_python(_wire(value)).model_dump(mode='json')
    except (ValidationError, ValueError, TypeError):
        raise WorkflowError('INVALID_INPUT_FORMAT') from None


def _key(value: str) -> None:
    if not isinstance(value, str) or re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}', value) is None:
        raise WorkflowError('INVALID_INPUT_FORMAT')


def validate_runtime_event(value) -> dict:
    """Strict, bounded telemetry schema. No arbitrary strings or client fields."""
    if type(value) is not dict or set(value) != {'correlation_id', 'stage', 'code', 'attempt'}:
        raise WorkflowError('INVALID_INPUT_FORMAT')
    try:
        event = RunEvent(**value)
        # Runtime correlation is generated by AMLAgent, never a source ID/PAN.
        if re.fullmatch(r'run-[0-9a-f]{32}', event.correlation_id) is None:
            raise ValueError('INVALID_RUNTIME_CORRELATION')
        return event.to_dict()
    except (TypeError, ValueError):
        raise WorkflowError('INVALID_INPUT_FORMAT') from None


SCHEMA = '''
CREATE TABLE IF NOT EXISTS jobs (
 job_id TEXT PRIMARY KEY, owner_subject TEXT NOT NULL, status TEXT NOT NULL,
 revision INTEGER NOT NULL, payload_json TEXT NOT NULL, request_json TEXT NOT NULL,
 engine TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS reports (
 report_id TEXT NOT NULL, report_version INTEGER NOT NULL, job_id TEXT NOT NULL REFERENCES jobs(job_id),
 owner_subject TEXT NOT NULL, content_sha256 TEXT NOT NULL, payload_json TEXT NOT NULL,
 PRIMARY KEY(report_id, report_version), UNIQUE(job_id));
CREATE TABLE IF NOT EXISTS decisions (
 decision_id TEXT PRIMARY KEY, report_id TEXT NOT NULL, report_version INTEGER NOT NULL,
 revision INTEGER NOT NULL, owner_subject TEXT NOT NULL, payload_json TEXT NOT NULL,
 FOREIGN KEY(report_id,report_version) REFERENCES reports(report_id,report_version),
 UNIQUE(report_id,report_version,revision));
CREATE TABLE IF NOT EXISTS audit_events (
 event_id TEXT PRIMARY KEY, job_id TEXT NOT NULL REFERENCES jobs(job_id), actor_subject TEXT NOT NULL,
 event_code TEXT NOT NULL, occurred_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS runtime_events (
 job_id TEXT NOT NULL REFERENCES jobs(job_id), sequence INTEGER NOT NULL,
 correlation_id TEXT NOT NULL, stage TEXT NOT NULL, event_code TEXT NOT NULL,
 attempt INTEGER NOT NULL, received_at TEXT NOT NULL,
 PRIMARY KEY(job_id, sequence));
CREATE TABLE IF NOT EXISTS idempotency (
 subject_id TEXT NOT NULL, operation TEXT NOT NULL, key TEXT NOT NULL,
 request_hash TEXT NOT NULL, response_json TEXT NOT NULL,
 PRIMARY KEY(subject_id,operation,key));
CREATE TABLE IF NOT EXISTS delivery_export_locks (
 report_id TEXT NOT NULL, report_version INTEGER NOT NULL, delivery_id TEXT NOT NULL,
 PRIMARY KEY(report_id,report_version),
 FOREIGN KEY(report_id,report_version) REFERENCES reports(report_id,report_version));
CREATE INDEX IF NOT EXISTS jobs_owner ON jobs(owner_subject);
CREATE INDEX IF NOT EXISTS jobs_status ON jobs(status);
CREATE INDEX IF NOT EXISTS decisions_report ON decisions(report_id,report_version,revision DESC);
'''


class SQLiteStore:
    def __init__(self, path: str | Path | None = None):
        profile = get_qa_profile()
        if path is None:
            path = (profile.workflow_dir if profile else WORKFLOW_ROOT) / 'workflow.sqlite3'
        candidate = Path(path).absolute()
        root = (profile.workflow_dir if profile else WORKFLOW_ROOT).absolute()
        # Resolve both lexical and actual containment before any write. Reject
        # links even when they currently resolve inside the permitted directory.
        if not candidate.is_relative_to(root) or '..' in candidate.parts:
            raise WorkflowError('INVALID_INPUT_FORMAT')
        for parent in [candidate, *candidate.parents]:
            if parent.is_symlink() or (hasattr(parent, 'is_junction') and parent.is_junction()):
                raise WorkflowError('INVALID_INPUT_FORMAT')
            if parent == root.parent:
                break
        if not candidate.resolve().is_relative_to(root.resolve()):
            raise WorkflowError('INVALID_INPUT_FORMAT')
        if candidate.exists() and (not candidate.is_file() or candidate.stat().st_nlink != 1):
            raise WorkflowError('INVALID_INPUT_FORMAT')
        self.path = candidate
        try:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with closing(self._connect()) as connection:
                connection.execute('PRAGMA journal_mode=WAL')
                connection.executescript(SCHEMA)
        except sqlite3.Error:
            raise WorkflowError('NOT_READY') from None

    def _connect(self):
        connection = sqlite3.connect(str(self.path), timeout=2, isolation_level=None)
        connection.row_factory = sqlite3.Row
        connection.execute('PRAGMA foreign_keys=ON')
        connection.execute('PRAGMA busy_timeout=2000')
        connection.execute('PRAGMA synchronous=FULL')
        return connection

    @contextmanager
    def transaction(self):
        connection = None
        try:
            connection = self._connect()
            connection.execute('BEGIN IMMEDIATE')
            yield connection
            connection.execute('COMMIT')
        except sqlite3.IntegrityError:
            if connection is not None and connection.in_transaction:
                connection.rollback()
            raise WorkflowError('INVALID_STATE') from None
        except sqlite3.Error:
            if connection is not None and connection.in_transaction:
                connection.rollback()
            raise WorkflowError('NOT_READY') from None
        except BaseException:
            if connection is not None and connection.in_transaction:
                connection.rollback()
            raise
        finally:
            if connection is not None:
                connection.close()

    @staticmethod
    def authorize_job(connection, job_id, principal: Principal, *, allow_supervisor=True):
        row = connection.execute('SELECT * FROM jobs WHERE job_id=?', (job_id,)).fetchone()
        if row is None:
            raise WorkflowError('NOT_FOUND')
        if row['owner_subject'] != principal.subject_id and not (allow_supervisor and principal.role == 'supervisor'):
            raise WorkflowError('FORBIDDEN')
        return row

    @staticmethod
    def get_report_row(connection, report_id, version, principal: Principal, *, allow_supervisor=True):
        row = connection.execute('SELECT * FROM reports WHERE report_id=? AND report_version=?',
                                 (report_id, version)).fetchone()
        if row is None:
            raise WorkflowError('NOT_FOUND')
        if row['owner_subject'] != principal.subject_id and not (allow_supervisor and principal.role == 'supervisor'):
            raise WorkflowError('FORBIDDEN')
        try:
            payload = _validated('InvestigationResult', json.loads(row['payload_json']))
        except (ValueError, TypeError):
            raise WorkflowError('INTERNAL_ERROR') from None
        if (payload['status'] != 'draft' or canonical_digest(payload) != row['content_sha256']
                or payload['report_id'] != row['report_id'] or payload['report_version'] != row['report_version']):
            raise WorkflowError('INTERNAL_ERROR')
        return row

    @staticmethod
    def _read_job_row(connection, row) -> dict:
        """Reject accidental storage inconsistency before publishing a job."""
        try:
            payload = validate_job(json.loads(row['payload_json'])).model_dump(mode='json')
            if any(payload[field] != row[field] for field in ('job_id', 'status', 'revision')):
                raise ValueError('ROW_MISMATCH')
            request = _validated('CreateJobRequest', json.loads(row['request_json']))
            if request['incident_id'] != payload['incident_id']:
                raise ValueError('REQUEST_MISMATCH')
            if payload['status'] == 'succeeded':
                report = payload['result']
                saved = connection.execute('SELECT * FROM reports WHERE job_id=?', (row['job_id'],)).fetchone()
                if (saved is None or saved['owner_subject'] != row['owner_subject']
                        or saved['report_id'] != report['report_id'] or saved['report_version'] != report['report_version']
                        or canonical_digest(report) != saved['content_sha256']
                        or canonical_digest(json.loads(saved['payload_json'])) != saved['content_sha256']):
                    raise ValueError('REPORT_MISMATCH')
            return payload
        except (ValueError, TypeError, KeyError):
            raise WorkflowError('INTERNAL_ERROR') from None

    @staticmethod
    def latest_decision_row(connection, report_id, version):
        return connection.execute('SELECT * FROM decisions WHERE report_id=? AND report_version=? '
                                  'ORDER BY revision DESC LIMIT 1', (report_id, version)).fetchone()

    @staticmethod
    def idempotent_response(connection, principal, operation, key, payload):
        _key(key)
        row = connection.execute('SELECT * FROM idempotency WHERE subject_id=? AND operation=? AND key=?',
                                 (principal.subject_id, operation, key)).fetchone()
        if row is None:
            return None
        if row['request_hash'] != canonical_digest(payload):
            raise WorkflowError('IDEMPOTENCY_CONFLICT')
        return json.loads(row['response_json'])

    @staticmethod
    def remember_idempotency(connection, principal, operation, key, payload, response):
        _key(key)
        connection.execute('INSERT INTO idempotency VALUES (?,?,?,?,?)',
                           (principal.subject_id, operation, key, canonical_digest(payload), _json(response)))

    @staticmethod
    def add_event(connection, job_id, principal, event_code):
        if re.fullmatch(r'[A-Z][A-Z0-9_]{0,63}', event_code) is None:
            raise WorkflowError('INVALID_INPUT_FORMAT')
        event_id = 'event-' + uuid.uuid4().hex
        connection.execute('INSERT INTO audit_events VALUES (?,?,?,?,?)',
                           (event_id, job_id, principal.subject_id, event_code, utc_now()))
        return event_id

    @staticmethod
    def _runtime_event_row(row) -> dict:
        try:
            event = validate_runtime_event({'correlation_id': row['correlation_id'],
                'stage': row['stage'], 'code': row['event_code'], 'attempt': row['attempt']})
            if (type(row['sequence']) is not int or not 1 <= row['sequence'] <= MAX_RUNTIME_EVENTS
                    or instant(row['received_at']).tzinfo is None):
                raise ValueError('INVALID_RUNTIME_EVENT_ROW')
            return {'job_id': row['job_id'], 'sequence': row['sequence'],
                    'received_at': row['received_at'], 'event': event}
        except (ValueError, TypeError, KeyError):
            raise WorkflowError('INTERNAL_ERROR') from None

    def append_runtime_event(self, job_id, sequence, event) -> dict:
        """Trusted controller only: preserve an observed prefix, including timeout.

        Sequence replays are idempotent. Timestamps come from the parent store;
        they mean durable receipt, not an assertion about a child wall clock.
        A terminal job may receive already observed events while its writer
        drains; this never changes that job or publishes a late report.
        """
        event = validate_runtime_event(event)
        if type(sequence) is not int or not 1 <= sequence <= MAX_RUNTIME_EVENTS:
            raise WorkflowError('INVALID_INPUT_FORMAT')
        with self.transaction() as connection:
            if connection.execute('SELECT 1 FROM jobs WHERE job_id=?', (job_id,)).fetchone() is None:
                raise WorkflowError('NOT_FOUND')
            existing = connection.execute('SELECT * FROM runtime_events WHERE job_id=? AND sequence=?',
                                          (job_id, sequence)).fetchone()
            if existing is not None:
                record = self._runtime_event_row(existing)
                if record['event'] != event:
                    raise WorkflowError('VERSION_CONFLICT')
                return record
            previous = connection.execute('SELECT * FROM runtime_events WHERE job_id=? ORDER BY sequence DESC LIMIT 1',
                                          (job_id,)).fetchone()
            expected = previous['sequence'] + 1 if previous is not None else 1
            if sequence != expected:
                raise WorkflowError('VERSION_CONFLICT')
            if previous is not None and self._runtime_event_row(previous)['event']['correlation_id'] != event['correlation_id']:
                raise WorkflowError('INVALID_STATE')
            received_at = utc_now()
            connection.execute('INSERT INTO runtime_events VALUES (?,?,?,?,?,?,?)',
                               (job_id, sequence, event['correlation_id'], event['stage'], event['code'],
                                event['attempt'], received_at))
            return {'job_id': job_id, 'sequence': sequence, 'received_at': received_at, 'event': event}

    def list_runtime_events(self, job_id, principal) -> list[dict]:
        """Owner/supervisor authorized read, with strict revalidation on storage."""
        with self.transaction() as connection:
            self.authorize_job(connection, job_id, principal)
            records = [self._runtime_event_row(row) for row in connection.execute(
                'SELECT * FROM runtime_events WHERE job_id=? ORDER BY sequence', (job_id,))]
            if (len(records) > MAX_RUNTIME_EVENTS
                    or [record['sequence'] for record in records] != list(range(1, len(records) + 1))
                    or len({record['event']['correlation_id'] for record in records}) > 1):
                raise WorkflowError('INTERNAL_ERROR')
            return records

    def create_job(self, request: CreateJobRequest | dict, principal: Principal, idempotency_key: str,
                   timeout_seconds=180, *, engine='template') -> dict:
        request = _validated('CreateJobRequest', request)
        if (type(timeout_seconds) not in (int, float) or not math.isfinite(timeout_seconds)
                or not 0 < timeout_seconds <= 180 or engine not in ('template', 'local-model')):
            raise WorkflowError('INVALID_INPUT_FORMAT')
        payload = {'request': request, 'engine': engine, 'timeout_seconds': float(timeout_seconds)}
        with self.transaction() as connection:
            replay = self.idempotent_response(connection, principal, 'create_job', idempotency_key, payload)
            if replay is not None:
                return replay
            now = datetime.now(timezone.utc)
            following = {'schema_version': '1.0', 'job_id': 'job-' + uuid.uuid4().hex,
                         'incident_id': request['incident_id'], 'status': 'queued', 'revision': 0,
                         'accepted_at': now.isoformat(timespec='microseconds').replace('+00:00', 'Z'),
                         'deadline_at': (now + timedelta(seconds=timeout_seconds)).isoformat(timespec='microseconds').replace('+00:00', 'Z')}
            following = _validated('Job', following)
            connection.execute('INSERT INTO jobs VALUES (?,?,?,?,?,?,?)',
                               (following['job_id'], principal.subject_id, 'queued', 0, _json(following), _json(request), engine))
            self.add_event(connection, following['job_id'], principal, 'JOB_ACCEPTED')
            self.remember_idempotency(connection, principal, 'create_job', idempotency_key, payload, following)
            return following

    def lookup_job_replay(self, request, principal, idempotency_key, *, timeout_seconds=180, engine='template'):
        """Replay lookup precedes readiness/admission checks; never starts work."""
        request = _validated('CreateJobRequest', request)
        if (type(timeout_seconds) not in (int, float) or not math.isfinite(timeout_seconds)
                or not 0 < timeout_seconds <= 180 or engine not in ('template', 'local-model')):
            raise WorkflowError('INVALID_INPUT_FORMAT')
        payload = {'request': request, 'engine': engine, 'timeout_seconds': float(timeout_seconds)}
        with self.transaction() as connection:
            return self.idempotent_response(connection, principal, 'create_job', idempotency_key, payload)

    def get_job(self, job_id, principal) -> dict:
        with self.transaction() as connection:
            return self._read_job_row(connection, self.authorize_job(connection, job_id, principal))

    def get_job_internal(self, job_id) -> dict:
        with self.transaction() as connection:
            row = connection.execute('SELECT * FROM jobs WHERE job_id=?', (job_id,)).fetchone()
            if row is None:
                raise WorkflowError('NOT_FOUND')
            return self._read_job_row(connection, row)

    def get_request_internal(self, job_id) -> dict:
        with self.transaction() as connection:
            row = connection.execute('SELECT request_json FROM jobs WHERE job_id=?', (job_id,)).fetchone()
            if row is None:
                raise WorkflowError('NOT_FOUND')
            return _validated('CreateJobRequest', json.loads(row['request_json']))

    def get_engine_internal(self, job_id) -> str:
        with self.transaction() as connection:
            row = connection.execute('SELECT engine FROM jobs WHERE job_id=?', (job_id,)).fetchone()
            if row is None:
                raise WorkflowError('NOT_FOUND')
            return row['engine']

    def _transition(self, connection, job_id, expected_revision, following):
        if type(expected_revision) is not int or expected_revision < 0:
            raise WorkflowError('INVALID_INPUT_FORMAT')
        row = connection.execute('SELECT * FROM jobs WHERE job_id=?', (job_id,)).fetchone()
        if row is None:
            raise WorkflowError('NOT_FOUND')
        previous = self._read_job_row(connection, row)
        if row['revision'] != expected_revision:
            raise WorkflowError('VERSION_CONFLICT')
        following = _validated('Job', following)
        if following['status'] in ('succeeded', 'refused', 'failed') and instant(utc_now()) >= instant(previous['deadline_at']):
            raise WorkflowError('DEADLINE_EXCEEDED')
        try:
            validate_job_transition(previous, following)
        except (ValueError, ValidationError):
            raise WorkflowError('INVALID_STATE') from None
        if following['status'] == 'succeeded':
            report = following['result']
            connection.execute('INSERT INTO reports VALUES (?,?,?,?,?,?)',
                               (report['report_id'], report['report_version'], job_id, row['owner_subject'],
                                canonical_digest(report), _json(report)))
        changed = connection.execute('UPDATE jobs SET status=?,revision=?,payload_json=? WHERE job_id=? AND revision=?',
                                     (following['status'], following['revision'], _json(following), job_id, expected_revision))
        if changed.rowcount != 1:
            raise WorkflowError('VERSION_CONFLICT')
        self.add_event(connection, job_id, Principal('local-worker'), 'JOB_' + following['status'].upper())
        return following

    def transition_job(self, job_id, expected_revision, following: dict) -> dict:
        """Trusted worker only; routes must not expose arbitrary transitions."""
        with self.transaction() as connection:
            return self._transition(connection, job_id, expected_revision, following)

    def cancel_job(self, job_id, principal, expected_revision=None, idempotency_key=None) -> dict:
        payload = {'job_id': job_id, 'expected_revision': expected_revision}
        operation = 'cancel_job:' + job_id
        with self.transaction() as connection:
            row = self.authorize_job(connection, job_id, principal)
            if idempotency_key is not None:
                replay = self.idempotent_response(connection, principal, operation, idempotency_key, payload)
                if replay is not None:
                    return replay
            previous = json.loads(row['payload_json'])
            if expected_revision is not None and row['revision'] != expected_revision:
                raise WorkflowError('VERSION_CONFLICT')
            if previous['status'] not in ACTIVE:
                raise WorkflowError('INVALID_STATE')
            following = dict(previous, status='cancelled', revision=previous['revision'] + 1, completed_at=utc_now())
            result = self._transition(connection, job_id, previous['revision'], following)
            self.add_event(connection, job_id, principal, 'CANCELLATION_REQUESTED')
            if idempotency_key is not None:
                self.remember_idempotency(connection, principal, operation, idempotency_key, payload, result)
            return result

    def list_jobs(self, principal) -> list[dict]:
        with self.transaction() as connection:
            query = 'SELECT * FROM jobs'
            rows = connection.execute(query + ' ORDER BY rowid DESC' if principal.role == 'supervisor' else
                                      query + ' WHERE owner_subject=? ORDER BY rowid DESC',
                                      () if principal.role == 'supervisor' else (principal.subject_id,))
            return [self._read_job_row(connection, row) for row in rows]

    def list_active_jobs(self) -> list[dict]:
        with self.transaction() as connection:
            return [self._read_job_row(connection, row) for row in connection.execute(
                "SELECT * FROM jobs WHERE status IN ('queued','running') ORDER BY rowid")]

    def recover_active_jobs(self) -> list[dict]:
        """Trusted single-coordinator startup only, after acquiring its OS lease."""
        recovered = []
        with self.transaction() as connection:
            rows = connection.execute("SELECT * FROM jobs WHERE status IN ('queued','running')").fetchall()
            for row in rows:
                previous = json.loads(row['payload_json'])
                now = utc_now()
                following = dict(previous, revision=previous['revision'] + 1, completed_at=now)
                if instant(now) >= instant(previous['deadline_at']):
                    following['status'] = 'timed_out'
                else:
                    following.update(status='failed', result={
                        'schema_version': '1.0', 'status': 'error', 'generated_at': now,
                        'correlation_id': 'recovery-' + uuid.uuid4().hex, 'code': 'DEPENDENCY_UNAVAILABLE',
                        'message': 'Local worker stopped before completion. Start a new investigation.', 'retryable': True})
                recovered.append(self._transition(connection, row['job_id'], row['revision'], following))
        return recovered

    def get_report(self, report_id, version, principal) -> dict:
        with self.transaction() as connection:
            return json.loads(self.get_report_row(connection, report_id, version, principal)['payload_json'])

    def report_ref(self, report_id, version, principal) -> ReportRef:
        with self.transaction() as connection:
            row = self.get_report_row(connection, report_id, version, principal)
            return ReportRef(report_id=report_id, report_version=version, content_sha256=row['content_sha256'])

    def decision_revision(self, report_id, version, principal) -> int:
        with self.transaction() as connection:
            self.get_report_row(connection, report_id, version, principal)
            row = self.latest_decision_row(connection, report_id, version)
            return row['revision'] if row else 0

    def latest_decision(self, report_id, version, principal) -> dict | None:
        with self.transaction() as connection:
            self.get_report_row(connection, report_id, version, principal)
            row = self.latest_decision_row(connection, report_id, version)
            return _validated('DecisionRecord', json.loads(row['payload_json'])) if row else None

    def report_review_state(self, report_id: str, report_version: int, principal: Principal) -> dict:
        """Authorized snapshot of the decision and its durable export lock.

        Acceptance freezes a report before delivery publication, so neither a
        pending nor a failed outbox entry establishes whether it is editable.
        Use the same lock table as create_decision, in the same transaction as
        the latest decision read. Later writes still enforce their own guards.
        """
        with self.transaction() as connection:
            self.get_report_row(connection, report_id, report_version, principal)
            row = self.latest_decision_row(connection, report_id, report_version)
            latest = _validated('DecisionRecord', json.loads(row['payload_json'])) if row else None
            locked = connection.execute(
                'SELECT 1 FROM delivery_export_locks WHERE report_id=? AND report_version=?',
                (report_id, report_version)).fetchone() is not None
            return {'latest_decision': latest, 'decision_locked': locked}

    def create_decision(self, report_id, request: DecisionRequest | dict, principal, idempotency_key) -> dict:
        request = _validated('DecisionRequest', request)
        if report_id != request['report']['report_id']:
            raise WorkflowError('INVALID_INPUT_FORMAT')
        operation = 'create_decision:' + report_id
        with self.transaction() as connection:
            reference = request['report']
            row = self.get_report_row(connection, report_id, reference['report_version'], principal, allow_supervisor=False)
            replay = self.idempotent_response(connection, principal, operation, idempotency_key, request)
            if replay is not None:
                return replay
            if reference['content_sha256'] != row['content_sha256']:
                raise WorkflowError('VERSION_CONFLICT')
            latest = self.latest_decision_row(connection, report_id, reference['report_version'])
            revision = latest['revision'] if latest else 0
            if revision != request['expected_revision']:
                raise WorkflowError('VERSION_CONFLICT')
            if connection.execute('SELECT 1 FROM delivery_export_locks WHERE report_id=? AND report_version=?',
                                  (report_id, reference['report_version'])).fetchone():
                raise WorkflowError('INVALID_STATE')
            event_id = self.add_event(connection, row['job_id'], principal, 'DECISION_RECORDED')
            record = _validated('DecisionRecord', {
                'schema_version': '1.0', 'decision_id': 'decision-' + uuid.uuid4().hex,
                'incident_id': json.loads(row['payload_json'])['incident_id'], 'report': reference,
                'previous_revision': revision, 'revision': revision + 1, 'action': request['action'],
                'reason': request['reason'], 'actor': principal.actor(), 'decided_at': utc_now(), 'audit_event_id': event_id})
            connection.execute('INSERT INTO decisions VALUES (?,?,?,?,?,?)',
                               (record['decision_id'], report_id, reference['report_version'], record['revision'],
                                principal.subject_id, _json(record)))
            self.remember_idempotency(connection, principal, operation, idempotency_key, request, record)
            return record

    def get_decision(self, decision_id, principal) -> dict:
        with self.transaction() as connection:
            row = connection.execute('SELECT * FROM decisions WHERE decision_id=?', (decision_id,)).fetchone()
            if row is None:
                raise WorkflowError('NOT_FOUND')
            self.get_report_row(connection, row['report_id'], row['report_version'], principal)
            return _validated('DecisionRecord', json.loads(row['payload_json']))
