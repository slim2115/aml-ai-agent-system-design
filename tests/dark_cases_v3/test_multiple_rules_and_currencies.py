EXPECTED_TOTALS = {
    "USD": ("1500012.30", ("TX-8800", "TX-8801")),
    "RUB": ("100.05", ("TX-8802",)),
}
EXPECTED_RULES = {
    "R-AML-010": ("2024-rev3", "115-ФЗ, ст.6, п.5"),
    "R-AML-015": ("2024-rev3", "115-ФЗ, ст.7, п.4"),
}


def assess(result, selected):
    """Compare report and retrieval to literals, not values generated by runtime."""
    issues = []
    if result.get("status") != "draft" or result.get("incident_id") != "INC-000250":
        return ["NOT_EXPECTED_DRAFT"]
    sums = []
    counts = []
    for fact in result.get("found_facts", []):
        for evidence in fact.get("evidence", []):
            if evidence.get("kind") == "sum":
                sums.append((evidence.get("currency"), evidence.get("value"),
                             fact.get("fact"),
                             tuple(sorted(evidence.get("tx_ids", [])))))
            elif evidence.get("kind") == "count":
                counts.append((evidence.get("value"), fact.get("fact"), tuple(sorted(evidence.get("tx_ids", [])))))
    window = "[2026-07-01T00:00:00Z, 2026-07-20T00:00:00Z)"
    expected_sums = sorted((c, value,
                            f"Сумма всех транзакций в контексте в валюте {c} за окно {window}, "
                            f"включая все статусы: {value} {c}.", tuple(sorted(ids)))
                           for c, (value, ids) in EXPECTED_TOTALS.items())
    if Counter(sums) != Counter(expected_sums):
        issues.append("SUMS_MISMATCH")
    if counts != [(3, f"Количество всех транзакций в контексте за окно {window}, включая все статусы: 3.",
                   ("TX-8800", "TX-8801", "TX-8802"))]:
        issues.append("COUNT_MISMATCH")
    if len(selected) != 2 or set(selected) != set(EXPECTED_RULES):
        issues.append("SELECTED_RULES_MISMATCH")
    rules = []
    for rule in result.get("applicable_rules", []):
        citation = rule.get("citation", {})
        rules.append((citation.get("rule_id"), citation.get("rule_version"),
                      citation.get("source_ref")))
    expected_rules = sorted((rule_id, version, ref)
                            for rule_id, (version, ref) in EXPECTED_RULES.items())
    if Counter(rules) != Counter(expected_rules):
        issues.append("REPORT_RULES_MISMATCH")
    return issues


@pytest.fixture(scope="module")
def multi_rule_observation(tmp_path_factory):
    scenario = next(s for s in load_catalog().cases if s.case.id == "QA-S03")
    source = DEFAULT_FOLDER / scenario.fixture
    target = tmp_path_factory.mktemp("multi-rule") / "snapshot"
    shutil.copytree(source, target)
    policy_path = target / "policy.json"
    policy = json.loads(policy_path.read_text(encoding="utf-8"))
    # An artificial mapping to exercise two rules: not an expert-approved policy.
    policy["applicability"]["high_risk_country"] = ["R-AML-010", "R-AML-015"]
    policy_path.write_text(json.dumps(policy, ensure_ascii=False), encoding="utf-8")
    with pytest.MonkeyPatch.context() as patch:
        # Runtime deliberately refuses source directories outside its root.
        patch.setattr(runtime_context, "PROJECT_ROOT", target.parent)
        return run_scenario(scenario, target)


def test_runtime_preserves_two_manual_currency_totals_and_two_rules(multi_rule_observation):
    assert assess(multi_rule_observation.result, multi_rule_observation.selected_rule_ids) == []


@pytest.mark.parametrize("mutation", ["value", "currency", "tx_ids", "duplicate_sum", "count", "text", "count_text"])
def test_oracle_rejects_aggregate_distortion(multi_rule_observation, mutation):
    result = deepcopy(multi_rule_observation.result)
    evidence = [e for fact in result["found_facts"] for e in fact["evidence"]]
    first_sum = next(e for e in evidence if e["kind"] == "sum")
    if mutation == "value":
        first_sum["value"] = "0.00"
    elif mutation == "currency":
        first_sum["currency"] = "EUR"
    elif mutation == "tx_ids":
        first_sum["tx_ids"] = []
    elif mutation == "duplicate_sum":
        result["found_facts"].append({"evidence": [deepcopy(first_sum)]})
    elif mutation == "text":
        next(f for f in result["found_facts"] if first_sum in f["evidence"])["fact"] = "Неверная сумма."
    elif mutation == "count_text":
        next(f for f in result["found_facts"] if any(e["kind"] == "count" for e in f["evidence"]))["fact"] = "Неверное количество."
    else:
        next(e for e in evidence if e["kind"] == "count")["value"] = 2
    expected = "COUNT_MISMATCH" if mutation in ("count", "count_text") else "SUMS_MISMATCH"
    assert expected in assess(result, multi_rule_observation.selected_rule_ids)


@pytest.mark.parametrize("mutation", ["missing", "duplicate", "wrong_version", "wrong_ref", "wrong_selected"])
def test_oracle_rejects_rule_distortion(multi_rule_observation, mutation):
    result = deepcopy(multi_rule_observation.result)
    selected = list(multi_rule_observation.selected_rule_ids)
    if mutation == "missing":
        result["applicable_rules"].pop()
    elif mutation == "duplicate":
        result["applicable_rules"].append(deepcopy(result["applicable_rules"][0]))
    elif mutation == "wrong_version":
        result["applicable_rules"][0]["citation"]["rule_version"] = "invented"
    elif mutation == "wrong_ref":
        result["applicable_rules"][0]["citation"]["source_ref"] = "invented"
    else:
        selected.pop()
    expected = "SELECTED_RULES_MISMATCH" if mutation == "wrong_selected" else "REPORT_RULES_MISMATCH"
    assert expected in assess(result, selected)


def test_oracle_does_not_accept_error_as_success():
    assert assess({"status": "error"}, []) == ["NOT_EXPECTED_DRAFT"]
